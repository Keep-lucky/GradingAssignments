def template_labels() -> tuple[str, ...]:
    """返回下拉菜单使用的题型标签。"""
    return tuple(template.name for template in PROMPT_TEMPLATES)


def get_template(name: str) -> PromptTemplate:
    """按题型标签取得只读预设。"""
    for template in PROMPT_TEMPLATES:
        if template.name == name:
            return template
    raise KeyError(f"未知 Prompt 预设：{name}")
